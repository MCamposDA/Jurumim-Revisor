"""
--context: <input>_report/context/, the files a language model (Claude, Gemini)
reads to answer questions about one run and to suggest screening decisions.

  README.md                 what the folder holds and the rules for the model
  overview.md               search, PRISMA counts, options, top words, network, trends
  records.csv               one row per record: IDs, year, title, journal, type, screening columns
  abstracts.md              title and abstract of every record, under its record_id
  network_terms.csv         words of the network, with community and the records using them
  network_links.csv         pairs of words, with direction counts and the records using them
  trends.csv                articles with each followed term per year (long format)
  methods_en.txt            the methods text of the report
  suggestions_template.csv  records not yet screened, to be filled in by the model
                            and read back with --import-suggestions

Nine files at most, all plain text, so they can also be uploaded to a chat
(a Claude project, a Gemini Gem).
"""
import csv
import shutil
from collections import Counter
from datetime import date
from pathlib import Path

MAX_IDS = 25          # record IDs listed per word or pair
N_PALAVRAS = 40
N_LIGACOES = 30
COLUNAS_TRIAGEM = ['screening_decision', 'exclusion_reason', 'rules_suggestion', 'rules_reason',
                   'ai_suggestion', 'ai_reason']

LEIAME = """# Jurumim Revisor context

Files written by `Jurumim_Revisor.py --context` from {fonte}, on {data}.
They describe one literature search: what was found, how it was screened so far,
and the word patterns of titles and abstracts.

| File | Content |
|---|---|
| overview.md | search, PRISMA counts, analysis options, most frequent words, network communities, trends |
| records.csv | one row per record: record_id, PMID, DOI, year, first author, title, journal, document type, language, databases, screening columns of the PRISMA table |
| abstracts.md | title and abstract of every record, under `## [record_id]` |
| network_terms.csv | words of the co-occurrence network: frequency, articles, community, degree, record IDs |
| network_links.csv | pairs of words seen side by side: count in each order, record IDs |
| trends.csv | number and share of the year's articles containing each followed term |
| methods_en.txt | methods text generated by the tool ([brackets] = to be completed) |
| suggestions_template.csv | records still without a screening decision |

## Rules for a language model reading this folder

1. You suggest; the researcher decides. Never present a suggestion as a decision,
   and never write into `screening_decision`.
2. Every statement about the literature cites the record IDs it comes from, as
   `[record_id]`. If no record supports it, say so.
3. Screening suggestions follow the researcher's criteria. Ask for them when they
   are not given. Use only `include`, `exclude` or `maybe`; use `maybe` when the
   title and abstract are not enough.
4. Return suggestions as a CSV with the columns of `suggestions_template.csv`:
   `record_id,title,suggestion,reason,evidence,model`. `evidence` is a short quote
   of the title or abstract; `model` is your model name. The researcher loads it with

       python Jurumim_Revisor.py --import-suggestions suggestions.csv {prisma}

   which fills the `ai_*` columns of the PRISMA table, next to the researcher's own.
5. Network and trend patterns are counts of words in titles and abstracts, not
   findings of the studies. Describe them as such.
"""


def _escrever_csv(caminho, colunas, linhas):
    with open(caminho, 'w', newline='', encoding='utf-8') as f:
        w = csv.writer(f)
        w.writerow(colunas)
        w.writerows(linhas)


def _valor(x):
    """Empty cell for None and NaN (years without articles)."""
    return '' if x is None or x != x else x


def _ids(artigos, indices):
    """Record IDs of a set of indices, most recent first, at most MAX_IDS."""
    ordem = sorted(indices, key=lambda i: (-(artigos[i]['ano'] or 0), artigos[i]['id']))
    ids = [artigos[i]['id'] for i in ordem[:MAX_IDS]]
    return ' '.join(ids) + (f" (+{len(indices) - MAX_IDS})" if len(indices) > MAX_IDS else '')


def ler_triagem(caminho_prisma):
    """{record_id: {screening and suggestion columns}} of the PRISMA table, or {}."""
    if not caminho_prisma:
        return {}
    from openpyxl import load_workbook
    wb = load_workbook(caminho_prisma, read_only=True)
    linhas = list(wb['records'].iter_rows(values_only=True))
    wb.close()
    cab = [str(c) for c in linhas[0]]
    colunas = [c for c in COLUNAS_TRIAGEM if c in cab]
    saida = {}
    for d in linhas[1:]:
        rid = str(d[cab.index('record_id')] or '').strip()
        rid = rid[:-2] if rid.endswith('.0') else rid
        saida[rid] = {c: ('' if d[cab.index(c)] is None else str(d[cab.index(c)])) for c in colunas}
    return saida



def _periodos(artigos, indices):
    """Share of articles with the term up to the median year and after it (None when not computable)."""
    anos = sorted(a['ano'] for a in artigos if a['ano'])
    if len(set(anos)) < 2:
        return None
    meio = anos[len(anos) // 2]
    if meio == anos[-1]:
        meio = anos[-1] - 1
    antes = [i for i, a in enumerate(artigos) if a['ano'] and a['ano'] <= meio]
    depois = [i for i, a in enumerate(artigos) if a['ano'] and a['ano'] > meio]
    if not antes or not depois:
        return None
    pa = 100 * sum(1 for i in antes if i in indices) / len(antes)
    pd_ = 100 * sum(1 for i in depois if i in indices) / len(depois)
    return anos[0], meio, anos[-1], pa, pd_


def _visao_geral(fonte, artigos, G, freq, art_termo, termos, contagens, log, caminho_prisma, analise, opcoes,
                 triagem):
    L = [f"# Overview: {fonte}", '',
         f"{len(artigos):,} records analysed (title and abstract). Generated on {date.today().isoformat()}.", '']

    L += ['## Search', '']
    if log:
        for o in log.get('sources', []):
            if o['origin'] == 'api':
                L.append(f"- {o['database']}: API{' (' + o['key'] + ')' if o.get('key') else ''}, "
                         f"{o['date']}, query `{o['query']}`, {o['records']:,} records")
            else:
                L.append(f"- {o['database']}: file {o['file']}, {o['records']:,} records "
                         f"(query and date not recorded)")
        L.append(f"- Identified {log['identified']:,}; duplicates removed {log['duplicates']['total']:,}; "
                 f"unique {log['unique']:,}; without abstract set apart {log['without_abstract']:,}"
                 + (' (kept in the analysis)' if log.get('kept_without_abstract') else ''))
    else:
        L.append('- No search log found next to the input (it is written by --merge and -p --db).')
    L.append('')

    L += ['## Screening (PRISMA table)', '']
    if contagens:
        c = contagens
        L.append(f"- Table: {Path(caminho_prisma).name}")
        L.append(f"- Records screened {c['triados']:,}: included {c['incluidos']:,}, excluded "
                 f"{c['excluidos'] + c['sem_resumo']:,} ({c['sem_resumo']:,} without abstract), maybe "
                 f"{c['talvez']:,}, not yet screened {c['pendentes']:,}")
        for col, rotulo in (('rules_suggestion', 'Rule suggestions (--suggest)'),
                            ('ai_suggestion', 'AI suggestions (--import-suggestions)')):
            n = Counter(v.get(col, '') for v in triagem.values() if v.get(col))
            if n:
                L.append(f"- {rotulo}: " + ', '.join(f"{k} {v:,}" for k, v in sorted(n.items())))
    else:
        L.append('- No PRISMA table found next to the input (it is written by --merge and -p --db).')
    L.append('')

    L += ['## Analysis options', '',
          f"- Lemmatisation: {'yes' if analise['lemma'] else 'no'}; extra stopwords: {analise['extra_stopwords']}",
          f"- Terms followed in trends: {', '.join(termos) if termos else 'none'}"
          + ('' if (opcoes['ws'] is not None or opcoes['grupos']) else
             ' (chosen automatically: most frequent words present in at most half of the records)'),
          f"- Network: pairs seen at least {opcoes['minimo']} times, at most {opcoes['max_nos']} words"
          + (', generic words kept' if opcoes['manter_genericas'] else ''), '']

    L += [f'## Most frequent words (top {N_PALAVRAS})', '',
          'Word: occurrences in titles and abstracts / records containing it. Stopwords and generic words excluded.',
          '']
    L.append(', '.join(f"{t} {n:,}/{len(art_termo[t]):,}" for t, n in freq.most_common(N_PALAVRAS)))
    L.append('')

    L += ['## Co-occurrence network', '']
    if G.number_of_nodes():
        L.append(f"{G.number_of_nodes():,} words and {G.number_of_edges():,} links. Communities (Louvain), "
                 f"largest first, with their most frequent words:")
        L.append('')
        comunidades = {}
        for t in sorted(G.nodes, key=lambda t: -G.nodes[t]['frequency']):
            comunidades.setdefault(G.nodes[t]['community'], []).append(t)
        for c, membros in sorted(comunidades.items()):
            L.append(f"- Community {c + 1} ({len(membros)} words): {', '.join(membros[:12])}")
        L += ['', f"Strongest links (top {N_LIGACOES}): the pair as it is usually written, times seen side by side:", '']
        arestas = sorted(G.edges(data=True), key=lambda e: -e[2]['weight'])[:N_LIGACOES]
        itens = []
        for a, b, d in arestas:
            a, b = (a, b) if a == d['term_a'] else (b, a)
            primeiro, segundo = (a, b) if d['a_before_b'] >= d['b_before_a'] else (b, a)
            itens.append(f"{primeiro} {segundo} ({d['weight']})")
        L.append(', '.join(itens))
    else:
        L.append(f"No pair of words appears {opcoes['minimo']} times.")
    L.append('')

    L += ['## Trends', '']
    if termos:
        L.append('Share of records containing each term, up to the median publication year and after it:')
        L.append('')
        for rotulo, indices in termos.items():
            p = _periodos(artigos, indices)
            if p:
                L.append(f"- {rotulo}: {p[3]:.1f}% ({p[0]}-{p[1]}) -> {p[4]:.1f}% ({p[1] + 1}-{p[2]}); "
                         f"{len(indices):,} records")
        anos = Counter(a['ano'] for a in artigos if a['ano'])
        if anos:
            L += ['', 'Records per year: ' + ', '.join(f"{y} {anos[y]}" for y in sorted(anos))]
    L.append('')
    return '\n'.join(L)


def escrever(destino, entrada, artigos, G, freq, art_termo, art_par, termos, tabelas_tend, contagens, log,
             caminho_prisma, analise, opcoes):
    pasta = Path(destino) / 'context'
    pasta.mkdir(exist_ok=True)
    fonte = Path(entrada).name
    triagem = ler_triagem(caminho_prisma)

    (pasta / 'README.md').write_text(LEIAME.format(fonte=fonte, data=date.today().isoformat(),
                                                   prisma=Path(caminho_prisma).name if caminho_prisma
                                                   else '<merged>_prisma.xlsx'), encoding='utf-8')
    (pasta / 'overview.md').write_text(_visao_geral(fonte, artigos, G, freq, art_termo, termos, contagens, log,
                                                    caminho_prisma, analise, opcoes, triagem), encoding='utf-8')

    colunas_triagem = [c for c in COLUNAS_TRIAGEM if any(c in v for v in triagem.values())]
    _escrever_csv(pasta / 'records.csv',
                  ['record_id', 'pmid', 'doi', 'year', 'first_author', 'title', 'journal', 'document_type',
                   'language', 'databases', 'has_abstract'] + colunas_triagem,
                  [[a['id'], a['id'] if a['id'].isdigit() else '', a['doi'] or '', a['ano'] or '', a['autor'],
                    a['titulo'], a['revista'], '; '.join(a['tipos']), '; '.join(a['linguas']),
                    '; '.join(sorted(a['bases'])), 'yes' if a['resumo'] else 'no']
                   + [triagem.get(a['id'], {}).get(c, '') for c in colunas_triagem] for a in artigos])

    blocos = []
    for a in artigos:
        cab = f"## [{a['id']}] {a['titulo']}"
        meta = ' | '.join(x for x in (str(a['ano'] or ''), a['autor'], a['revista'],
                                      f"doi:{a['doi']}" if a['doi'] else '') if x)
        blocos.append(f"{cab}\n{meta}\n\n{a['resumo'] or '(no abstract)'}\n")
    (pasta / 'abstracts.md').write_text(f"# Titles and abstracts ({len(artigos):,} records of {fonte})\n\n"
                                        + '\n'.join(blocos), encoding='utf-8')

    if G.number_of_nodes():
        _escrever_csv(pasta / 'network_terms.csv',
                      ['term', 'frequency', 'articles', 'community', 'degree', 'record_ids'],
                      [[t, d['frequency'], d['articles'], d['community'] + 1, d['degree'], _ids(artigos, art_termo[t])]
                       for t, d in sorted(G.nodes(data=True), key=lambda x: -x[1]['frequency'])])
        linhas = []
        for a, b, d in sorted(G.edges(data=True), key=lambda e: -e[2]['weight']):
            a, b = (a, b) if a == d['term_a'] else (b, a)
            linhas.append([a, b, d['weight'], d['a_before_b'], d['b_before_a'], d['articles'],
                           _ids(artigos, art_par[frozenset((a, b))])])
        _escrever_csv(pasta / 'network_links.csv',
                      ['term_a', 'term_b', 'cooccurrences', 'a_before_b', 'b_before_a', 'articles', 'record_ids'],
                      linhas)

    base, contagem, parte, janela = tabelas_tend
    if base is not None:
        linhas = []
        for termo in [c for c in contagem.columns if c != 'year']:
            for k, ano in enumerate(contagem['year']):
                linhas.append([ano, termo, contagem[termo][k], _valor(parte[termo][k]), _valor(janela[termo][k])])
        _escrever_csv(pasta / 'trends.csv', ['year', 'term', 'articles', 'share_percent', 'share_3yr_percent'],
                      linhas)

    if (Path(destino) / 'methods_en.txt').is_file():
        shutil.copyfile(Path(destino) / 'methods_en.txt', pasta / 'methods_en.txt')

    pendentes = [a for a in artigos if not triagem.get(a['id'], {}).get('screening_decision')]
    _escrever_csv(pasta / 'suggestions_template.csv',
                  ['record_id', 'title', 'suggestion', 'reason', 'evidence', 'model'],
                  [[a['id'], a['titulo'], '', '', '', ''] for a in pendentes])
    return pasta, len(pendentes)
